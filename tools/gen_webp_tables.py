#!/usr/bin/env python3
"""Extracts the VP8 constant tables from libwebp's decoder sources (BSD licence, https://github.com/webmproject/libwebp)
into modules/codecs/.../WebpTables.scala, avoiding hand transcription.

    tools/gen_webp_tables.py <libwebp checkout or directory holding src/dec/tree_dec.c and quant_dec.c>
"""
import re, sys, os
root = sys.argv[1]
def array(path, name):
    s = open(os.path.join(root, path)).read()
    m = re.search(r"\b" + name + r"\s*(\[[^=]*\])\s*=\s*\{", s)
    i = m.end() - 1
    depth = 0
    for j in range(i, len(s)):
        if s[j] == "{": depth += 1
        elif s[j] == "}":
            depth -= 1
            if depth == 0: break
    body = re.sub(r"//.*", "", s[i:j + 1])
    return [int(x) for x in re.findall(r"-?\d+", body)]
tables = {
    "DcTable": array("src/dec/quant_dec.c", "kDcTable"),
    "AcTable": array("src/dec/quant_dec.c", "kAcTable"),
    "CoeffsProba0": array("src/dec/tree_dec.c", "CoeffsProba0"),
    "CoeffsUpdateProba": array("src/dec/tree_dec.c", "CoeffsUpdateProba"),
    "BModesProba": array("src/dec/tree_dec.c", "kBModesProba"),
}
assert len(tables["DcTable"]) == 128 and len(tables["AcTable"]) == 128
assert len(tables["CoeffsProba0"]) == 1056 and len(tables["CoeffsUpdateProba"]) == 1056 and len(tables["BModesProba"]) == 900
out = ["// GENERATED by tools/gen_webp_tables.py from libwebp (BSD licence, Copyright Google Inc.) - do not edit.",
       "package scalaui.codecs", "", "/** VP8 constant tables: quantizer steps, default/update token probabilities and 4x4 intra-mode contexts. */",
       "private[codecs] object WebpTables:"]
for name, vals in tables.items():
    chunks = [vals[i:i + 24] for i in range(0, len(vals), 24)]
    out.append(f"  val {name}: Array[Int] = Array(")
    out.append(",\n".join("    " + ", ".join(str(v) for v in c) for c in chunks))
    out.append("  )")
open(os.path.join(os.path.dirname(__file__), "../modules/codecs/src/main/scala/scalaui/codecs/WebpTables.scala"), "w").write("\n".join(out) + "\n")
print("ok", {k: len(v) for k, v in tables.items()})
