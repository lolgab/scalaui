#!/usr/bin/env python3
"""Generates modules/window/.../KeysymTable.scala from X11's keysymdef.h: keysym names, values and Unicode equivalents.
usage: tools/gen_keysyms.py [path/to/keysymdef.h]"""
import re, sys, os
src = sys.argv[1] if len(sys.argv) > 1 else "/opt/homebrew/include/X11/keysymdef.h"
rx = re.compile(r"#define\s+XK_(\w+)\s+0x([0-9a-fA-F]+)(?:\s*/\*(.*?)\*/)?")
rows = []
seen = set()
for line in open(src, encoding="utf-8", errors="replace"):
    m = rx.match(line)
    if not m: continue
    name, val, comment = m.group(1), int(m.group(2), 16), m.group(3) or ""
    if name in seen: continue
    seen.add(name)
    u = re.search(r"U\+([0-9A-Fa-f]{4,6})", comment)
    # the 0x01000000 + codepoint range is Unicode by definition
    cp = int(u.group(1), 16) if u else (val - 0x01000000 if 0x01000100 <= val <= 0x0110ffff else None)
    if cp is None and 0x20 <= val <= 0x7e or (cp is None and 0xa0 <= val <= 0xff): cp = val
    rows.append(f"{name},{val:x}," + (f"{cp:x}" if cp is not None else ""))
chunks, cur = [], []
size = 0
for r in rows:
    if size + len(r) + 1 > 30000:
        chunks.append(cur); cur = []; size = 0
    cur.append(r); size += len(r) + 1
chunks.append(cur)
out = ["package scalaui.window", "", "/** GENERATED by tools/gen_keysyms.py from X11 keysymdef.h: `name,keysym,unicode` records. */",
       "private[window] object KeysymTable:", "  val chunks: Array[String] = Array("]
out.append(",\n".join('    "' + ";".join(c) + '"' for c in chunks))
out.append("  )")
dest = os.path.join(os.path.dirname(__file__), "..", "modules/window/src/main/scala/scalaui/window/KeysymTable.scala")
open(dest, "w").write("\n".join(out) + "\n")
print("wrote", len(rows), "keysyms in", len(chunks), "chunks")
