#!/usr/bin/env python3
"""Generate modules/unicode ZawgyiData.scala from google/myanmartools (Apache-2.0).

usage: gen_zawgyi.py TransliterateZ2U.java zawgyiUnicodeModel.dat > ZawgyiData.scala
Fetch inputs with:
  gh api repos/googlei18n/myanmar-tools/contents/clients/java/src/main/java/com/google/myanmartools/TransliterateZ2U.java --jq .content | base64 -d
  gh api repos/googlei18n/myanmar-tools/contents/clients/java/src/main/resources/com/google/myanmartools/zawgyiUnicodeModel.dat --jq .content | base64 -d
"""
import base64, re, sys

src = open(sys.argv[1], encoding="utf-8").read()
model = open(sys.argv[2], "rb").read()

# rules: addRule(new Rule("pat", "sub")[.setMatchOnStart()][.setRevisitPosition(n)]);
phases = {}
for m in re.finditer(r'phase(\d+)\.addRule\(new Rule\("((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\)\s*((?:\.set\w+\([^)]*\)\s*)*)\);', src):
    n, pat, sub, mods = int(m[1]), m[2], m[3], m[4]
    mos = "true" if "setMatchOnStart" in mods else "false"
    rv = re.search(r"setRevisitPosition\((\d+)\)", mods)
    phases.setdefault(n, []).append((pat, sub, mos, rv[1] if rv else "-1"))

def esc(s):
    # Java \uXXXX escapes are valid in Scala string literals as well; escape '$'-free text as is
    return s

out = []
out.append("package scalaui.unicode\n")
out.append("// GENERATED by tools/gen_zawgyi.py from googlei18n/myanmar-tools (Apache License 2.0,")
out.append("// Copyright 2017 Google LLC). See NOTICE in modules/unicode. Do not edit.\n")
out.append("private[unicode] object ZawgyiData:")
out.append("  final case class Rule(pattern: String, substitution: String, matchOnStart: Boolean, revisit: Int)")
out.append("  val z2u: Array[Array[Rule]] = Array(")
ps = []
for n in sorted(phases):
    rules = ",\n".join('    Rule("%s", "%s", %s, %s)' % (esc(p), esc(s), mo, rv) for p, s, mo, rv in phases[n])
    ps.append("  Array(\n" + rules + "\n  )")
out.append(",\n".join(ps))
out.append("  )\n")
b = base64.b64encode(model).decode()
chunks = [b[i:i+100] for i in range(0, len(b), 100)]
out.append("  /** Serialized Markov model (UZMODEL v2), base64. */")
out.append("  val modelBase64: String = Seq(")
out.append(",\n".join('    "%s"' % c for c in chunks))
out.append("  ).mkString")
print("\n".join(out))
