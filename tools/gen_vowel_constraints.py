#!/usr/bin/env python3
"""Extracts the vowel-sequence constraints (pairs after which a dotted circle is inserted) from HarfBuzz's
hb-ot-shaper-vowel-constraints.cc into modules/shaping/.../VowelConstraintData.scala.

    tools/gen_vowel_constraints.py hb-ot-shaper-vowel-constraints.cc

HarfBuzz is distributed under the "Old MIT" licence: https://github.com/harfbuzz/harfbuzz/blob/main/COPYING
The data itself derives from the Universal Shaping Engine script development specification.
"""
import re, sys, os

src = open(sys.argv[1]).read()
iso = {"DEVANAGARI": "Deva", "BENGALI": "Beng", "GURMUKHI": "Guru", "GUJARATI": "Gujr", "ORIYA": "Orya", "TAMIL": "Taml",
       "TELUGU": "Telu", "KANNADA": "Knda", "MALAYALAM": "Mlym", "SINHALA": "Sinh", "BRAHMI": "Brah", "KHOJKI": "Khoj",
       "KHUDAWADI": "Sind", "TIRHUTA": "Tirh", "MODI": "Modi", "TAKRI": "Takr"}
blocks = re.split(r"\n    case HB_SCRIPT_", src)[1:]
data = {}
for b in blocks:
    name = b.split(":")[0]
    body = b.split("\n    case HB_SCRIPT_")[0]
    pairs = []
    # tokenise the block into events
    events = re.findall(r"case 0x([0-9A-Fa-f]+)u:|switch \(buffer->cur \(1\)\.codepoint\)|matched = true;|matched = 0x([0-9A-Fa-f]+)u == buffer->cur \(1\)\.codepoint;|if \(0x([0-9A-Fa-f]+)u == buffer->cur \(\)\.codepoint &&\s*0x([0-9A-Fa-f]+)u == buffer->cur \(1\)\.codepoint\)", body)
    # re.findall with alternation loses which branch matched; do a manual scan instead
    toks = re.finditer(r"case 0x([0-9A-Fa-f]+)u:|(switch \(buffer->cur \(1\)\.codepoint\))|(matched = true;)|matched = 0x([0-9A-Fa-f]+)u == buffer->cur \(1\)\.codepoint;|if \(0x([0-9A-Fa-f]+)u == buffer->cur \(\)\.codepoint &&\s*0x([0-9A-Fa-f]+)u == buffer->cur \(1\)\.codepoint\)", body)
    firsts, seconds, in_inner, last_was_case = [], [], False, False
    for t in toks:
        if t.group(1):
            c = int(t.group(1), 16)
            if in_inner: seconds.append(c)
            else:
                if not last_was_case: firsts = []
                firsts.append(c)
            last_was_case = True
            continue
        last_was_case = False
        if t.group(2): in_inner = True; seconds = []
        elif t.group(3) and in_inner:
            pairs += [(a, s) for a in firsts for s in seconds]; in_inner = False
        elif t.group(4):
            pairs += [(a, int(t.group(4), 16)) for a in firsts]
        elif t.group(5):
            pairs.append((int(t.group(5), 16), int(t.group(6), 16)))
    triple = None
    m = re.search(r"case 0x([0-9A-Fa-f]+)u:\s*if \(0x([0-9A-Fa-f]+)u == buffer->cur \(1\)\.codepoint &&\s*buffer->idx \+ 2 < count &&\s*0x([0-9A-Fa-f]+)u == buffer->cur \(2\)\.codepoint\)", body)
    if m: triple = tuple(int(x, 16) for x in m.groups())
    data[iso[name]] = (sorted(set(pairs)), triple)

out = ["// GENERATED by tools/gen_vowel_constraints.py from HarfBuzz hb-ot-shaper-vowel-constraints.cc (Old MIT licence).",
       "package scalaui.shaping", "",
       "/** Vowel sequences that look like another vowel: a dotted circle is inserted between the pair. */",
       "private[shaping] object VowelConstraintData:",
       "  val pairs: Map[String, Array[Int]] = Map("]
out.append(",\n".join('    "%s" -> Array(%s)' % (k, ", ".join("0x%X" % x for p in v[0] for x in p)) for k, v in sorted(data.items())))
out.append("  )")
out.append("  /** Sequences of three (first, second, third) where the dotted circle goes between second and third. */")
out.append("  val triples: Map[String, Array[Int]] = Map(" + ", ".join('"%s" -> Array(%s)' % (k, ", ".join("0x%X" % x for x in v[1])) for k, v in sorted(data.items()) if v[1]) + ")")
dst = os.path.join(os.path.dirname(__file__), "../modules/shaping/src/main/scala/scalaui/shaping/VowelConstraintData.scala")
open(dst, "w").write("\n".join(out) + "\n")
print({k: len(v[0]) for k, v in data.items()}, {k: v[1] for k, v in data.items() if v[1]})
